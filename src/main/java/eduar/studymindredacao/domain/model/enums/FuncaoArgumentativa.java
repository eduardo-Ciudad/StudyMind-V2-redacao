package eduar.studymindredacao.domain.model.enums;

/** O que o repertório ajuda a fazer dentro do argumento. Usado como filtro na tela de Repertório. */
public enum FuncaoArgumentativa {
    /** Explicar a causa do problema. */
    EXPLAIN_CAUSE,
    /** Explicar as consequências do problema. */
    EXPLAIN_CONSEQUENCE,
    /** Mostrar desigualdade entre grupos. */
    SHOW_INEQUALITY,
    /** Mostrar a invisibilidade de um grupo ou trabalho. */
    SHOW_INVISIBILITY,
    /** Definir um conceito. */
    DEFINE_CONCEPT,
    /** Fazer crítica social. */
    SOCIAL_CRITIQUE,
    /** Dar contexto histórico. */
    HISTORICAL_CONTEXT,
    /** Provar que o problema existe (dado, pesquisa). */
    PROVE_PROBLEM,
    /** Mostrar a distância entre a lei e a realidade. */
    LEGAL_GAP,
    /** Comparar realidades (outro país, outra época). */
    COMPARE_REALITY,
    /** Servir de exemplo concreto. */
    EXAMPLE,
    /** Sustentar a proposta de intervenção. */
    SUPPORT_INTERVENTION
}
